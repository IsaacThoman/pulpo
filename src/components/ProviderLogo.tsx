export type ProviderKey =
  | 'openai'
  | 'anthropic'
  | 'moonshot'
  | 'deepseek'
  | 'meta'
  | 'alibaba'
  | 'mistral'
  | 'xai'
  | 'grok'
  | 'unknown'

export function providerKey(provider: string): ProviderKey {
  const p = provider.toLowerCase()
  if (p.includes('openai')) return 'openai'
  if (p.includes('anthropic')) return 'anthropic'
  if (p.includes('moonshot') || p.includes('kimi')) return 'moonshot'
  if (p.includes('deepseek')) return 'deepseek'
  if (p.includes('meta')) return 'meta'
  if (p.includes('alibaba') || p.includes('qwen')) return 'alibaba'
  if (p.includes('mistral')) return 'mistral'
  if (p.includes('xai') || p.includes('x.ai')) return 'xai'
  if (p.includes('grok')) return 'grok'
  return 'unknown'
}

