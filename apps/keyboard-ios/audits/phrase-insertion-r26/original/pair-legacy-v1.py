#!/usr/bin/env python3
"""Preserve exposed R5/R20 oracles and all changed failed rows across real modes."""
import json,pathlib,sys,subprocess
suite,bfile,cfile,out=map(pathlib.Path,sys.argv[1:])
v=json.loads(suite.read_text()); cases=v['cases'] if isinstance(v,dict) else v
bs=json.loads(bfile.read_text());cs=json.loads(cfile.read_text())
keys={(c['id'],l) for c in cases for l in ['en_US','es','en_es']}
assert len(bs)==len(cs)==len(keys)
bm={(r['id'],r['language']):r for r in bs};cm={(r['id'],r['language']):r for r in cs}
assert set(bm)==set(cm)==keys
strings=set()
def collect(v):
 if isinstance(v,str):strings.add(v)
 elif isinstance(v,list):
  for x in v:collect(x)
 elif isinstance(v,dict):
  for x in v.values():collect(x)
collect(cases);collect(bs);collect(cs);strings=sorted(strings)
p=pathlib.Path('/tmp/pulpo-r26-legacy-graphemes.swift');p.write_text('import Foundation\nlet s = try JSONDecoder().decode([String].self, from: FileHandle.standardInput.readDataToEndOfFile())\nFileHandle.standardOutput.write(try JSONEncoder().encode(s.map { $0.map(String.init) }))\n')
r=subprocess.run(['swift',str(p)],input=json.dumps(strings).encode(),stdout=subprocess.PIPE,check=True)
g=dict(zip(strings,json.loads(r.stdout)))
def replay(result,case):
 errors=[]
 if 'prefix' in case:
  text=case['prefix']+case['selected']+case['suffix'];cur=len(g[case['prefix']]);selection=case['selected']
  for i,p in enumerate(result['primitives']):
   chars=list(text) if text not in g else g[text] # reconstruct Swift Characters from original components below when needed
   # All text generated by primitives is reconstructed as Character arrays directly.
   if i==0:chars=g[case['prefix']]+g[case['selected']]+g[case['suffix']]
   else:chars=state
   if p['cursor']!=cur or p['selected']!=selection:errors.append([i,'cursor/selection'])
   n=len(g[p['selected']]);value=g[p['text']]
   if p['kind']=='insert':removed=chars[cur:cur+n];state=chars[:cur]+value+chars[cur+n:];cur+=len(value)
   elif n:removed=chars[cur:cur+n];state=chars[:cur]+chars[cur+n:]
   else:removed=chars[max(0,cur-1):cur];state=chars[:max(0,cur-1)]+chars[cur:];cur=max(0,cur-1)
   if ''.join(removed)!=p['removed']:errors.append([i,'removed'])
   selection='';text=''.join(state)
  if (text,cur)!=(result['actual'],result['actualCaret']):errors.append(['final','document/caret'])
 else:
  text=case['initialLeft']+case['initialRight'];cur=len(g[case['initialLeft']]);sel=0
  for i,p in enumerate(result['primitives']):
   before=g[p['before']];a=p['caretBefore'];n=p['selectionBefore']
   if (text,cur,sel)!=(p['before'],a,n):errors.append([i,'chain'])
   if not 0<=a<=len(before) or not 0<=n<=len(before)-a:errors.append([i,'bounds']);continue
   if p['kind']=='insert':removed=before[a:a+n];after=before[:a]+g[p['value']]+before[a+n:];c=a+len(g[p['value']])
   elif n:removed=before[a:a+n];after=before[:a]+before[a+n:];c=a
   else:removed=before[max(0,a-1):a];after=before[:max(0,a-1)]+before[a:];c=max(0,a-1)
   if (''.join(after),c,''.join(removed))!=(p['after'],p['caretAfter'],p['removed']):errors.append([i,'replay'])
   text=p['after'];cur=p['caretAfter'];sel=p['selectionAfter']
  if (text,cur)!=(result['actual'],result['caret']):errors.append(['final','document/caret'])
 return errors
rows=[]
for c in cases:
 for lang in ['en_US','es','en_es']:
  b=bm[c['id'],lang];d=cm[c['id'],lang]; passed='exact' if 'exact' in b else 'passed'
  assert b['expected']==d['expected']==c['expected']
  if 'dictionary' in b:
   assert b['dictionary']==d['dictionary']==lang+'.pkdict' and b['dictionarySHA256']==d['dictionarySHA256'] and b['modelMode']==d['modelMode']==lang
  else:assert b['dictionaries']==d['dictionaries']
  changed=(b['actual'],b.get('actualCaret',b.get('caret')))!=(d['actual'],d.get('actualCaret',d.get('caret')))
  rows.append(dict(id=c['id'],language=lang,input=c,baseline=b,candidate=d,outputChanged=changed,gain=not b[passed] and d[passed],regression=b[passed] and not d[passed],changedFailure=changed and not b[passed] and not d[passed],baselineReplayErrors=replay(b,c),candidateReplayErrors=replay(d,c)))
summary=dict(cases=len(cases),executionsPerVersion=len(rows),baselineExact=sum(r['baseline'].get('exact',r['baseline'].get('passed')) for r in rows),candidateExact=sum(r['candidate'].get('exact',r['candidate'].get('passed')) for r in rows),gains=sum(r['gain'] for r in rows),regressions=sum(r['regression'] for r in rows),baselineUnavailable=sum(not r['baseline']['completed'] for r in rows),candidateUnavailable=sum(not r['candidate']['completed'] for r in rows),changedFailures=[(r['id'],r['language']) for r in rows if r['changedFailure']],replayFailures=sum(bool(r['baselineReplayErrors'] or r['candidateReplayErrors']) for r in rows))
pathlib.Path(out).write_text(json.dumps(dict(classification='Exposed development only; original oracles unchanged',summary=summary,rows=rows),ensure_ascii=False,separators=(',',':'))+'\n')
print(json.dumps(summary,indent=2));assert summary['replayFailures']==0
