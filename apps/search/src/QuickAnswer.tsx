import { Sparkles } from 'lucide-react'
import { useEffect, useId, useRef, useState } from 'react'
import { api, formatSearchPrice, SearchApiError, type QuickAnswerResponse } from './api'
import { safeHttpUrl } from './navigation'

type AnswerState =
  | { status: 'idle' | 'loading' }
  | { status: 'success'; data: QuickAnswerResponse }
  | { status: 'error'; error: SearchApiError }

function AnswerContent({ data }: { data: QuickAnswerResponse }) {
  const references = data.references.flatMap(reference => {
    const url = safeHttpUrl(reference.url)
    return url ? [{ ...reference, url }] : []
  })
  const citations = new Map(references.map(reference => [reference.index, reference]))
  return (
    <>
      <div className="quick-answer-text">{data.answer.split(/(\[\d{1,3}\]|\*\*[^*\n]+\*\*)/g).map((part, position) => {
        if (part.startsWith('**') && part.endsWith('**')) return <strong key={position}>{part.slice(2, -2)}</strong>
        const match = /^\[(\d{1,3})\]$/.exec(part)
        const citation = match && citations.get(Number(match[1]))
        return citation
          ? <a key={position} aria-label={`Source ${citation.index}, ${citation.title || citation.url.hostname}`}
              href={citation.url.href} target="_blank" rel="noreferrer">{part}</a>
          : part
      })}</div>
      {references.length > 0 && <ul className="quick-answer-sources" aria-label="Answer sources">
        {references.map(reference => <li key={reference.index}>
          <a href={reference.url.href} target="_blank" rel="noreferrer">
            [{reference.index}] {reference.title || reference.url.hostname}
          </a>
        </li>)}
      </ul>}
      <a className="quick-answer-provider" href="https://help.kagi.com/kagi/api/fastgpt.html" target="_blank" rel="noreferrer">Generated by Kagi FastGPT</a>
    </>
  )
}

export function QuickAnswer({ query, priceMicros, pulpoOrigin }: { query: string; priceMicros: number; pulpoOrigin: string }) {
  const [state, setState] = useState<AnswerState>({ status: 'idle' })
  const [expanded, setExpanded] = useState(false)
  const active = useRef<AbortController | null>(null)
  const id = useId()
  const headingId = id + '-title'

  useEffect(() => () => active.current?.abort(), [])

  async function requestAnswer() {
    if (active.current) return
    const controller = new AbortController()
    active.current = controller
    setState({ status: 'loading' })
    try {
      const data = await api.quickAnswer(query, controller.signal)
      if (!controller.signal.aborted) setState({ status: 'success', data })
    } catch (error) {
      if (!controller.signal.aborted) setState({ status: 'error', error: error instanceof SearchApiError ? error
        : new SearchApiError('The quick answer is temporarily unavailable.', 0) })
    } finally {
      active.current = null
    }
  }

  return (
    <div className="quick-answer">
      <button className="secondary-button" aria-expanded={expanded} aria-controls={id} onClick={() => {
        setExpanded(!expanded)
        if (!expanded && state.status === 'idle') void requestAnswer()
      }}>
        <Sparkles size={15} aria-hidden="true" />
        {expanded ? 'Hide quick answer' : 'Quick answer'}
        {state.status === 'idle' && <span className="quick-answer-price">{formatSearchPrice(priceMicros)}</span>}
      </button>
      <section id={id} className="answer quick-answer-card" aria-labelledby={headingId} hidden={!expanded}>
        <h2 id={headingId}>Quick answer</h2>
        {state.status === 'loading' && <p role="status">Finding an answer with sources…</p>}
        {state.status === 'error' && (
          <div role="alert">
            <p>{state.error.message}</p>
            {state.error.status === 402
              ? <a className="secondary-button" href={pulpoOrigin}>Open Pulpo</a>
              : <button className="secondary-button" onClick={() => void requestAnswer()}>Try again</button>}
          </div>
        )}
        {state.status === 'success' && <AnswerContent data={state.data} />}
      </section>
    </div>
  )
}
