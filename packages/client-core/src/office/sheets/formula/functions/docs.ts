/**
 * Function metadata for the formula bar: autocomplete names, argument hints, and one-line
 * descriptions. Covers the library, the evaluator's control/reference functions, and the
 * text-format functions, so autocomplete is complete regardless of who implements a function.
 *
 * Entries are written as Excel-style signatures: `[arg]` is optional and a trailing `...` means
 * the last argument (or pair) repeats.
 */

export type FunctionCategory =
  | 'math'
  | 'statistical'
  | 'text'
  | 'logical'
  | 'lookup'
  | 'array'
  | 'datetime'
  | 'information'
  | 'financial'
  | 'engineering'
  | 'database'

export interface FunctionArgDoc {
  name: string
  optional?: boolean
  /** The argument may repeat (`number2, …`). */
  repeating?: boolean
}

export interface FunctionDoc {
  name: string
  category: FunctionCategory
  args: FunctionArgDoc[]
  description: string
}

