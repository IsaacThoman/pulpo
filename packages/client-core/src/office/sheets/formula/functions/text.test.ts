describe('numberToText (General rendering)', () => {
  it.each([
    [0, '0'],
    [1, '1'],
    [-1.5, '-1.5'],
    [1 / 3, '0.333333333333333'],
    [2 / 3, '0.666666666666667'],
    [0.1 + 0.2, '0.3'],
    [123456789012345, '123456789012345'],
    [1e15, '1E+15'],
    [2 ** 53, '9.00719925474099E+15'],
    [1e21, '1E+21'],
    [-1.5e100, '-1.5E+100'],
    [0.001, '0.001'],
    [0.000000001, '0.000000001'],
    [1e-10, '1E-10'],
    [1.23e-12, '1.23E-12'],
    [100, '100'],
    [1234.5678, '1234.5678'],
    [45000.5, '45000.5'],
  ])('%s → %s', (value, expected) => {
    expect(numberToText(value)).toBe(expected)
  })
})

