/** Every function's autocomplete entry, sorted by name. */
export const FUNCTION_DOCS: FunctionDoc[] = GROUPS.flatMap(([category, entries]) => entries.map(([signature, description]) => parseSignature(signature, description, category))).sort(
  (a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0),
)

const DOCS_BY_NAME = new Map(FUNCTION_DOCS.map((doc) => [doc.name, doc]))

/** The doc entry for a function name (case-insensitive, `_xlfn.` prefix allowed). */
export function functionDoc(name: string): FunctionDoc | undefined {
  return DOCS_BY_NAME.get(name.toUpperCase().replace(/^(_XLFN\.)?(_XLWS\.)?/, ''))
}
