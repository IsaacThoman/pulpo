/** Parses `NAME(arg1, [arg2], ...)` into a doc entry. */
function parseSignature(signature: string, description: string, category: FunctionCategory): FunctionDoc {
  const open = signature.indexOf('(')
  const name = signature.slice(0, open)
  const inner = signature.slice(open + 1, signature.lastIndexOf(')')).trim()
  const parts = inner ? inner.split(',').map((p) => p.trim()) : []
  const args: FunctionArgDoc[] = []
  for (const part of parts) {
    if (part === '...') {
      const last = args[args.length - 1]
      if (last) last.repeating = true
      continue
    }
    const optional = part.startsWith('[') && part.endsWith(']')
    const arg: FunctionArgDoc = { name: optional ? part.slice(1, -1) : part }
    if (optional) arg.optional = true
    args.push(arg)
  }
  return { name, category, args, description }
}

