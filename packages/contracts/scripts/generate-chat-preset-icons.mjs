import { writeFile } from 'node:fs/promises'
import dynamicIconImports from 'lucide-react/dynamicIconImports.mjs'

const canonicalNames = Object.entries(dynamicIconImports)
  .filter(([name, loadIcon]) => String(loadIcon).includes(`./icons/${name}.mjs`))
  .map(([name]) => name)
  .sort((left, right) => left.localeCompare(right))

const output = `// Generated by npm run generate:chat-preset-icons -w @pulpo/contracts. Do not edit manually.\n` +
  `export const CHAT_PRESET_ICON_NAMES = ${JSON.stringify(canonicalNames, null, 2)} as const\n`

await writeFile(new URL('../src/chat-preset-icons.generated.ts', import.meta.url), output)
